/**
 * Persistent design store shared by the canvas and the agent.
 *
 * The document lives in `useState`, so the chat tools can read and write the
 * same boards the overlay renders. A deep watcher saves to localStorage and,
 * in the desktop app, mirrors a readable copy into `.kodra/design/`.
 */

import { call, isTauri } from '../lib/api'
import {
  cloneBoard,
  createBoard,
  createDesign,
  designFileName,
  designMarkdown,
  boardMarkdown,
  parseDesign,
  type DesignBoard,
  type DesignDocument
} from '../lib/design'

export type DesignSyncState = 'local' | 'saving' | 'saved' | 'error'

export interface DesignSyncStatus {
  state: DesignSyncState
  at: number
  message: string
}

const STORAGE_PREFIX = 'kodra:design:'

let installed = false
let saveTimer: ReturnType<typeof setTimeout> | null = null
let syncTimer: ReturnType<typeof setTimeout> | null = null
let lastSignature = ''
let syncedKey = ''

function contentSignature(doc: DesignDocument): string {
  return JSON.stringify({
    ...doc,
    boards: doc.boards.map((board) => ({ ...board, view: undefined }))
  })
}

function storageKey(path: string | undefined | null): string {
  return `${STORAGE_PREFIX}${path ? encodeURIComponent(path) : '~'}`
}

export function designFiles(doc: DesignDocument): { path: string; text: string }[] {
  const content: DesignDocument = {
    ...doc,
    boards: doc.boards.map((board) => ({ ...board, view: undefined })) as unknown as DesignBoard[]
  }
  const active = doc.boards.find((board) => board.id === doc.activeBoardId)
  const names = uniqueFileNames(doc.boards)
  const index = [
    '# Kodra design',
    '',
    '> Generated by the Kodra design canvas. The canvas rewrites these files on save;',
    '> edit the design in Kodra or through the `write_design` agent tool instead.',
    '',
    `Active board: **${active?.name ?? 'none'}** · ${doc.boards.length} board${doc.boards.length === 1 ? '' : 's'}.`,
    '',
    '## Boards',
    '',
    ...doc.boards.map(
      (board, position) =>
        `- [${board.name}](${names[position]}) — ${board.device}, ${board.width}×${board.height}`
    ),
    '',
    'Machine-readable copy: `design.json`.',
    ''
  ].join('\n')

  const files = [{ path: '.kodra/design/README.md', text: index }]
  for (let position = 0; position < doc.boards.length; position++) {
    const board = doc.boards[position]!
    files.push({
      path: `.kodra/design/${names[position]}`,
      text: [
        `# ${board.name}`,
        '',
        `Board id: \`${board.id}\`. Device: ${board.device} (${board.width}×${board.height}). Theme: ${board.theme}.`,
        '',
        boardMarkdown(board).split('\n').slice(2).join('\n'),
        ''
      ].join('\n')
    })
  }
  files.push({
    path: '.kodra/design/design.json',
    text: `${JSON.stringify(content, null, 2)}\n`
  })
  return files
}

/** Two boards can share a name, so keep their generated files distinct. */
function uniqueFileNames(boards: DesignBoard[]): string[] {
  const used = new Set<string>()
  return boards.map((board) => {
    const base = designFileName(board).replace(/\.md$/, '')
    let name = base
    let suffix = 2
    while (used.has(name)) name = `${base}-${suffix++}`
    used.add(name)
    return `${name}.md`
  })
}

export function useDesign() {
  const ide = useIde()
  const doc = useState<DesignDocument>('kodra:design-doc', () => createDesign())
  /**
   * The active board lives in the document so the agent, the canvas and the
   * generated `.kodra/design` copy always agree on which screen is selected.
   */
  const activeBoardId = computed<string>({
    get: () => doc.value.activeBoardId,
    set: (id: string) => {
      if (id && doc.value.activeBoardId !== id) doc.value.activeBoardId = id
    }
  })
  const loadedKey = useState<string>('kodra:design-key', () => '')
  const revision = useState<number>('kodra:design-revision', () => 0)
  const origin = useState<'canvas' | 'agent' | 'system'>('kodra:design-origin', () => 'system')
  const sync = useState<DesignSyncStatus>('kodra:design-sync', () => ({
    state: 'local',
    at: 0,
    message: ''
  }))
  const open = useState<boolean>('kodra:design-open', () => false)
  const past = useState<string[]>('kodra:design-past', () => [])
  const future = useState<string[]>('kodra:design-future', () => [])

  const activeBoard = computed<DesignBoard | null>(
    () => doc.value.boards.find((board) => board.id === activeBoardId.value) ?? doc.value.boards[0] ?? null
  )

  const canUndo = computed(() => past.value.length > 0)
  const canRedo = computed(() => future.value.length > 0)

  function ensureActive(): void {
    if (!doc.value.boards.some((board) => board.id === activeBoardId.value)) {
      activeBoardId.value = doc.value.boards[0]?.id ?? ''
    }
  }

  function load(): void {
    const key = storageKey(ide.workspace.value?.path)
    if (loadedKey.value === key) return
    loadedKey.value = key
    let stored: string | null = null
    try {
      stored = localStorage.getItem(key)
    } catch {
      stored = null
    }
    const parsed = parseDesign(stored)
    doc.value = parsed ?? createDesign()
    ensureActive()
    past.value = []
    future.value = []
    revision.value++
    origin.value = 'system'
    lastSignature = contentSignature(doc.value)
  }

  function init(): void {
    load()
  }

  function persistNow(): void {
    if (saveTimer) {
      clearTimeout(saveTimer)
      saveTimer = null
    }
    try {
      localStorage.setItem(storageKey(ide.workspace.value?.path), JSON.stringify(doc.value))
    } catch {
      sync.value = { state: 'error', at: Date.now(), message: 'Browser storage is full.' }
      ide.notify('The design could not be saved: browser storage is full.', 'error')
    }
  }

  function schedulePersist(): void {
    if (saveTimer) clearTimeout(saveTimer)
    saveTimer = setTimeout(persistNow, 350)
  }

  let syncing = false
  let syncAgain = false

  async function syncNow(): Promise<void> {
    if (syncTimer) {
      clearTimeout(syncTimer)
      syncTimer = null
    }
    const workspace = ide.workspace.value
    if (!workspace || !isTauri()) {
      sync.value = {
        state: 'local',
        at: Date.now(),
        message: workspace ? 'Run the desktop app to mirror the design into the workspace.' : 'Open a workspace to mirror the design.'
      }
      return
    }
    if (syncing) {
      syncAgain = true
      return
    }
    syncing = true
    syncAgain = false
    sync.value = { state: 'saving', at: Date.now(), message: '' }
    try {
      for (const file of designFiles(doc.value)) {
        await call('write_file', { path: file.path, text: file.text })
      }
      syncedKey = storageKey(workspace.path)
      sync.value = { state: 'saved', at: Date.now(), message: '.kodra/design' }
    } catch (err) {
      sync.value = { state: 'error', at: Date.now(), message: String(err) }
    } finally {
      syncing = false
      if (syncAgain) void syncNow()
    }
  }

  function scheduleSync(): void {
    if (syncTimer) clearTimeout(syncTimer)
    syncTimer = setTimeout(() => void syncNow(), 1200)
  }

  /** Push the current document onto the shared undo stack. */
  function checkpoint(): void {
    origin.value = 'canvas'
    past.value = [...past.value.slice(-49), JSON.stringify(doc.value)]
    future.value = []
  }

  function undo(): void {
    const previous = past.value[past.value.length - 1]
    if (!previous) return
    const parsed = parseDesign(previous)
    if (!parsed) return
    future.value = [...future.value, JSON.stringify(doc.value)]
    past.value = past.value.slice(0, -1)
    origin.value = 'canvas'
    doc.value = parsed
    ensureActive()
  }

  function redo(): void {
    const next = future.value[future.value.length - 1]
    if (!next) return
    const parsed = parseDesign(next)
    if (!parsed) return
    past.value = [...past.value, JSON.stringify(doc.value)]
    future.value = future.value.slice(0, -1)
    origin.value = 'canvas'
    doc.value = parsed
    ensureActive()
  }

  function addBoard(device: DesignBoard['device'] = 'desktop'): DesignBoard {
    checkpoint()
    const board = createBoard(`Screen ${doc.value.boards.length + 1}`, device)
    doc.value.boards = [...doc.value.boards, board]
    activeBoardId.value = board.id
    return board
  }

  function duplicateBoard(id: string): DesignBoard | null {
    const source = doc.value.boards.find((board) => board.id === id)
    if (!source) return null
    checkpoint()
    const copy = cloneBoard(source, `${source.name} copy`)
    doc.value.boards = [...doc.value.boards, copy]
    activeBoardId.value = copy.id
    return copy
  }

  function removeBoard(id: string): boolean {
    if (doc.value.boards.length <= 1) return false
    const board = doc.value.boards.find((entry) => entry.id === id)
    if (!board) return false
    checkpoint()
    doc.value.boards = doc.value.boards.filter((entry) => entry.id !== id)
    ensureActive()
    return true
  }

  function setActiveBoard(id: string): void {
    if (doc.value.boards.some((board) => board.id === id)) activeBoardId.value = id
  }

  function markAgent(): void {
    origin.value = 'agent'
  }

  function copySpec(): string {
    return designMarkdown(doc.value)
  }

  function show(): void {
    load()
    open.value = true
    // Create the generated copy the first time a workspace is opened in this
    // session; later opens do not rewrite unchanged files.
    if (isTauri() && syncedKey !== storageKey(ide.workspace.value?.path)) void syncNow()
  }

  function hide(): void {
    open.value = false
  }

  function toggle(): void {
    if (open.value) hide()
    else show()
  }

  if (!installed) {
    installed = true
    watch(
      doc,
      () => {
        revision.value++
        schedulePersist()
        const signature = contentSignature(doc.value)
        if (signature !== lastSignature) {
          lastSignature = signature
          scheduleSync()
        }
      },
      { deep: true }
    )
    watch(
      () => ide.workspace.value?.path,
      () => {
        if (open.value) load()
        else {
          loadedKey.value = ''
          load()
        }
      }
    )
  }

  return {
    open,
    doc,
    activeBoard,
    activeBoardId,
    revision,
    origin,
    sync,
    past,
    future,
    canUndo,
    canRedo,
    init,
    load,
    persistNow,
    syncNow,
    checkpoint,
    undo,
    redo,
    addBoard,
    duplicateBoard,
    removeBoard,
    setActiveBoard,
    markAgent,
    copySpec,
    show,
    hide,
    toggle
  }
}
